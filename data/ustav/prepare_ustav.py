import re
import os

INPUT_FILE = "ustav_for_training.txt"
OUTPUT_FILE = "ustav_for_training_2.txt"


def count_tokens(text):
    return len(re.findall(r"\w+|[^\w\s]", text))


def preprocess_ustav(text):

    # 2. Убираем все виды скобок (круглые, квадратные, фигурные)
    text = re.sub(r"[\[\]\(\)\{\}]", "", text)

    # 3. Чиним частые ошибки сканирования (разорванные пробелом слова)
    ocr_fixes = {
        "из бранъ": "избранъ",
        "Само держцемъ": "Самодержцемъ",
        "Само держецъ": "Самодержецъ",
        "государ ствамъ": "государствамъ",
        "Нѣ мецкаго": "Нѣмецкаго",
        "переве сти": "перевести",
        "хи трости": "хитрости",
        "го сподарствахъ": "господарствахъ",
        "подо баетъ": "подобаетъ",
        "гото товы": "готовы",
        "призрѣ ніе": "призрѣніе",
        "прилежа ніемъ": "прилежаніемъ",
        "радѣ ніемъ": "радѣніемъ",
        "ника кому": "никакому",
        "уче ніемъ": "ученіемъ",
        "ны нѣшнихъ": "нынѣшнихъ",
        "пре мудрые": "премудрые",
        "соста вовъ": "составовъ",
        "на учены": "научены",
        "пря мымъ": "прямымъ",
        "зави стію": "завистію",
        "изы скано": "изыскано",
        "Иску шающийся": "Искушающийся",
        "пе речислены": "перечислены",
        "пред именитыхъ": "предименитыхъ",
        "под вигу": "подвигу",
        "желе за": "железа",
        "рукодѣль ному": "рукодѣльному",
        "отмѣс нія": "отмѣснія",
        "уряд ствахъ": "урядствахъ",
        "При става": "Пристава",
        "ста ны": "станы",
        "Чинона чальника": "Чиноначальника",
        "недру говъ": "недруговъ",
        "те легамъ": "телегамъ",
        "подъошевные": "подошвенные",
    }
    for bad, good in ocr_fixes.items():
        text = text.replace(bad, good)

    # 4. Убираем нумерацию оглавления (числа с точкой в начале строки)
    text = re.sub(r"^\s*\d+\.\s+", "", text, flags=re.MULTILINE)

    # 5. Склейка разорванных слов с дефисом
    text = re.sub(r"-\s*\n\s*", "", text)

    # 6. Склейка предложений (заменяем одинарный перенос на пробел)
    text = re.sub(r"(?<!\n)\n(?!\n)", " ", text)

    # 7. Фикс слипшейся пунктуации (например "введенія,особно")
    text = re.sub(r",([а-яА-Яa-zA-Zѣіѵѳ])", r", \1", text)

    # 8. Убираем лишние пробелы, которые могли появиться
    text = re.sub(r"\s+", " ", text)

    # 9. Разбиваем на предложения
    sentences = re.split(r"(?<=[.!?])\s+", text)

    return sentences


def main():
    if not os.path.exists(INPUT_FILE):
        print(f"❌ Файл {INPUT_FILE} не найден!")
        return

    with open(INPUT_FILE, "r", encoding="utf-8") as f:
        raw_text = f.read()

    print("🔧 Чистим Устав, лечим OCR-мусор и считаем токены...")
    sentences = preprocess_ustav(raw_text)

    cleaned_count = 0
    total_tokens = 0

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        for sentence in sentences:
            sentence = sentence.strip()
            # Берем только осмысленные предложения (длиннее 15 символов)
            if len(sentence) > 15:
                f.write(sentence + "\n")
                cleaned_count += 1
                total_tokens += count_tokens(sentence)

    print("\n" + "=" * 50)
    print(f"✨ Готово! Извлечено полноценных предложений: {cleaned_count}")
    print(f"📊 Всего токенов (слова + пунктуация): {total_tokens:,}")
    print(f"💾 Файл сохранен как: {OUTPUT_FILE}")
    print("=" * 50)


if __name__ == "__main__":
    main()
